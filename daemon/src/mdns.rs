//! Multicast DNS, so the router answers to `<hostname>.local`.
//!
//! avahi-daemon does the answering. `systemd-resolved` is masked on a Keystone
//! router because dnsmasq needs port 53, so networkd's `MulticastDNS=` has
//! nothing to hand the setting to. Keystone writes `avahi-daemon.conf` with an
//! `allow-interfaces` list taken from the interfaces that enable mDNS, runs the
//! service only while one does, and opens UDP 5353 on those interfaces in the
//! firewall (see `firewall::rules`).
//!
//! mDNS is link-local: a name is only resolvable from the segment it was
//! announced on.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

use anyhow::{Context, Result, anyhow};
use keystone_core::{InterfaceConfig, InterfaceRole, MdnsInputAccept, SystemdActiveState};
use tracing::{info, warn};

use crate::systemd;

/// Directory holding `avahi-daemon.conf`. Created by `ConfigurationDirectory=`
/// and writable in the daemon's sandbox through `ReadWritePaths=`.
const AVAHI_CONF_DIR: &str = "/etc/avahi";
pub const AVAHI_CONF_PATH: &str = "/etc/avahi/avahi-daemon.conf";
/// The packaged units. `avahi-daemon.service` requires the socket unit.
const SERVICE: &str = "avahi-daemon.service";
const SOCKET: &str = "avahi-daemon.socket";
/// UDP port multicast DNS uses.
pub const MDNS_PORT: u16 = 5353;

/// Interfaces that answer mDNS: enabled LAN links that ask for it. Sorted, so
/// the generated file and the firewall rule are stable.
pub fn mdns_interfaces(configs: &[InterfaceConfig]) -> Vec<String> {
    let mut names: Vec<String> = configs
        .iter()
        .filter(|c| c.enabled && c.mdns && c.role == InterfaceRole::LAN)
        .map(|c| c.name.clone())
        .collect();
    names.sort();
    names.dedup();
    names
}

/// The firewall accept for UDP 5353, or `None` while no interface uses mDNS.
pub fn input_accept(configs: &[InterfaceConfig]) -> Option<MdnsInputAccept> {
    let interfaces = mdns_interfaces(configs);
    (!interfaces.is_empty()).then_some(MdnsInputAccept { interfaces })
}

/// The `avahi-daemon.conf` text for `interfaces`. Every name is validated
/// first, because the file is line-based.
pub fn render_conf(interfaces: &[String]) -> Result<String> {
    for name in interfaces {
        keystone_core::validation::interface_name(name).map_err(|error| anyhow!(error))?;
    }
    Ok(format!(
        "# Generated by Keystone. Manual changes are overwritten.\n\
         [server]\n\
         use-ipv4=yes\n\
         use-ipv6=yes\n\
         allow-interfaces={}\n\
         \n\
         [publish]\n\
         publish-addresses=yes\n\
         publish-hinfo=no\n\
         publish-workstation=no\n\
         \n\
         [reflector]\n\
         enable-reflector=no\n\
         \n\
         [wide-area]\n\
         enable-wide-area=no\n\
         \n\
         [rlimits]\n\
         rlimit-core=0\n\
         rlimit-data=4194304\n\
         rlimit-fsize=0\n\
         rlimit-nofile=768\n\
         rlimit-stack=4194304\n\
         rlimit-nproc=3\n",
        interfaces.join(",")
    ))
}

/// The configuration that apply would write, or empty while mDNS is off. Used
/// by the pending-changes diff, so it matches what apply writes.
pub fn preview_conf(configs: &[InterfaceConfig]) -> Result<String> {
    let interfaces = mdns_interfaces(configs);
    if interfaces.is_empty() {
        return Ok(String::new());
    }
    render_conf(&interfaces)
}

/// Bring avahi-daemon in line with the interface configuration.
pub async fn apply(configs: &[InterfaceConfig]) -> Result<()> {
    let interfaces = mdns_interfaces(configs);
    if interfaces.is_empty() {
        disable().await;
        return Ok(());
    }

    let content = render_conf(&interfaces)?;
    let changed = fs::read_to_string(AVAHI_CONF_PATH).ok().as_deref() != Some(content.as_str());
    if changed {
        write_conf(&content)?;
    }
    if changed || !service_active().await {
        // A start that failed earlier (for example on a bad configuration)
        // leaves the units in start-limit-hit, which refuses any restart.
        for unit in [SOCKET, SERVICE] {
            if let Err(error) = systemd::reset_failed_unit(unit).await {
                info!("{unit} not reset: {error:#}");
            }
        }
        systemd::enable_unit(SERVICE)
            .await
            .context("failed to enable avahi-daemon.service (is the avahi package installed?)")?;
        systemd::restart_unit(SERVICE)
            .await
            .context("failed to restart avahi-daemon.service")?;
    }
    info!("mDNS applied on {}", interfaces.join(", "));
    Ok(())
}

/// Stop avahi-daemon. One that was never installed is not an error, and the
/// configuration file is left for the package to own again.
async fn disable() {
    // The socket would start the service again on the next connection.
    for unit in [SERVICE, SOCKET] {
        if service_state(unit).await == Some(SystemdActiveState::Active)
            && let Err(error) = systemd::stop_unit(unit).await
        {
            warn!("Stopping {unit} failed: {error:#}");
        }
    }
    if let Err(error) = systemd::disable_unit(SERVICE).await {
        // Disabling a unit that does not exist fails; that is the normal case
        // when avahi is not installed.
        info!("avahi-daemon not disabled: {error:#}");
    }
}

fn write_conf(content: &str) -> Result<()> {
    fs::create_dir_all(AVAHI_CONF_DIR)
        .with_context(|| format!("failed to create {AVAHI_CONF_DIR}"))?;
    let temporary = Path::new(AVAHI_CONF_DIR).join(".avahi-daemon.conf.tmp");
    fs::write(&temporary, content)
        .with_context(|| format!("failed to write {}", temporary.display()))?;
    fs::set_permissions(&temporary, fs::Permissions::from_mode(0o644))
        .with_context(|| format!("failed to set permissions on {}", temporary.display()))?;
    fs::rename(&temporary, AVAHI_CONF_PATH)
        .with_context(|| format!("failed to install {AVAHI_CONF_PATH}"))?;
    Ok(())
}

async fn service_active() -> bool {
    service_state(SERVICE).await == Some(SystemdActiveState::Active)
}

async fn service_state(unit: &str) -> Option<SystemdActiveState> {
    match systemd::get_unit_detail(unit).await {
        Ok(Some(detail)) => Some(detail.unit.active_state),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lan(name: &str, mdns: bool) -> InterfaceConfig {
        InterfaceConfig {
            name: name.to_string(),
            role: InterfaceRole::LAN,
            mdns,
            ..InterfaceConfig::default()
        }
    }

    #[test]
    fn only_enabled_lan_interfaces_that_ask_for_mdns_answer() {
        let mut off = lan("eth1", false);
        let mut disabled = lan("eth2", true);
        disabled.enabled = false;
        let mut wan = lan("eth0", true);
        wan.role = InterfaceRole::WAN;
        off.mdns = false;
        let configs = [lan("br0", true), off, disabled, wan, lan("eth3", true)];
        assert_eq!(mdns_interfaces(&configs), ["br0", "eth3"]);
    }

    #[test]
    fn no_accept_is_generated_while_nothing_uses_mdns() {
        assert_eq!(input_accept(&[lan("eth1", false)]), None);
        assert_eq!(
            input_accept(&[lan("eth1", true)]),
            Some(MdnsInputAccept {
                interfaces: vec!["eth1".to_string()]
            })
        );
    }

    #[test]
    fn conf_is_limited_to_the_chosen_interfaces() {
        let conf = render_conf(&["br0".to_string(), "eth3".to_string()]).unwrap();
        assert!(conf.contains("\nallow-interfaces=br0,eth3\n"));
        // The router must not relay mDNS between segments or answer
        // wide-area queries unasked.
        assert!(conf.contains("enable-reflector=no"));
        assert!(conf.contains("enable-wide-area=no"));
        assert_eq!(conf.matches("allow-interfaces").count(), 1);
    }

    /// avahi-daemon exits on a key in the wrong group, so every key must sit in
    /// the section avahi-daemon.conf(5) documents it under.
    #[test]
    fn every_key_is_in_the_section_avahi_expects() {
        let expected = [
            ("use-ipv4", "server"),
            ("use-ipv6", "server"),
            ("allow-interfaces", "server"),
            ("publish-addresses", "publish"),
            ("publish-hinfo", "publish"),
            ("publish-workstation", "publish"),
            ("enable-reflector", "reflector"),
            ("enable-wide-area", "wide-area"),
        ];
        let conf = render_conf(&["eth1".to_string()]).unwrap();
        let mut section = "";
        let mut seen = 0;
        for line in conf.lines().filter(|l| !l.starts_with('#')) {
            if let Some(name) = line.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
                section = name;
            } else if let Some((key, _)) = line.split_once('=') {
                if key.starts_with("rlimit-") {
                    assert_eq!(section, "rlimits", "{key}");
                } else {
                    let (_, want) = expected
                        .iter()
                        .find(|(k, _)| *k == key)
                        .unwrap_or_else(|| panic!("unexpected key {key}"));
                    assert_eq!(section, *want, "{key}");
                }
                seen += 1;
            }
        }
        assert!(seen >= expected.len());
    }

    #[test]
    fn conf_rejects_names_that_could_inject_lines() {
        assert!(render_conf(&["eth1\n[reflector]".to_string()]).is_err());
        assert!(render_conf(&["a,b".to_string()]).is_err());
    }

    #[test]
    fn preview_is_empty_while_mdns_is_off() {
        assert_eq!(preview_conf(&[lan("eth1", false)]).unwrap(), "");
        assert!(preview_conf(&[lan("eth1", true)]).unwrap().contains("eth1"));
    }
}
