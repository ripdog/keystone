//! The generated hostapd configuration.

use keystone_core::wireless::WirelessConfig;

/// Directory holding the per-interface hostapd configuration files. Created by
/// `ConfigurationDirectory=` in the daemon's unit.
pub const HOSTAPD_CONF_DIR: &str = "/etc/hostapd";

/// Path of the configuration file for `interface`. The caller has validated the
/// name, which cannot contain a path separator.
pub fn conf_path(interface: &str) -> String {
    format!("{HOSTAPD_CONF_DIR}/{interface}.conf")
}

/// The packaged template unit that runs one hostapd per interface.
pub fn unit_name(interface: &str) -> String {
    format!("hostapd@{interface}.service")
}

/// The `hostapd.conf` text for an enabled `config`. The caller has validated it,
/// so no value contains a line break.
///
/// The access point joins `bridge` itself once it is up: a wireless interface
/// cannot be enslaved while it is a station, so networkd must not do it.
pub fn render_hostapd_conf(config: &WirelessConfig) -> String {
    let flag = |value: bool| u8::from(value);
    let lines = [
        "# Generated by Keystone - do not edit manually".to_string(),
        format!("interface={}", config.interface),
        "driver=nl80211".to_string(),
        format!("bridge={}", config.bridge),
        format!("ssid={}", config.ssid),
        "utf8_ssid=1".to_string(),
        format!("ignore_broadcast_ssid={}", flag(config.hidden_ssid)),
        format!("country_code={}", config.country_code),
        "ieee80211d=1".to_string(),
        "hw_mode=g".to_string(),
        format!("channel={}", config.channel),
        "ieee80211n=1".to_string(),
        "wmm_enabled=1".to_string(),
        format!("ap_isolate={}", flag(config.client_isolation)),
        "macaddr_acl=0".to_string(),
        "auth_algs=1".to_string(),
        "wpa=2".to_string(),
        "wpa_key_mgmt=WPA-PSK".to_string(),
        "rsn_pairwise=CCMP".to_string(),
        format!("wpa_passphrase={}", config.passphrase),
    ];
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn config() -> WirelessConfig {
        WirelessConfig {
            enabled: true,
            interface: "wlp4s0b1".to_string(),
            bridge: "br-lan".to_string(),
            ssid: "keystone".to_string(),
            country_code: "NZ".to_string(),
            passphrase: "correct horse battery".to_string(),
            ..WirelessConfig::default()
        }
    }

    #[test]
    fn renders_a_wpa2_access_point_on_the_bridge() {
        let text = render_hostapd_conf(&config());
        for expected in [
            "interface=wlp4s0b1",
            "bridge=br-lan",
            "ssid=keystone",
            "country_code=NZ",
            "hw_mode=g",
            "channel=6",
            "wpa=2",
            "wpa_key_mgmt=WPA-PSK",
            "rsn_pairwise=CCMP",
            "wpa_passphrase=correct horse battery",
            "ignore_broadcast_ssid=0",
            "ap_isolate=0",
        ] {
            assert!(
                text.lines().any(|line| line == expected),
                "missing {expected:?} in:\n{text}"
            );
        }
        assert!(text.ends_with('\n'));
    }

    #[test]
    fn options_map_to_hostapd_flags() {
        let text = render_hostapd_conf(&WirelessConfig {
            hidden_ssid: true,
            client_isolation: true,
            channel: 11,
            ..config()
        });
        assert!(text.lines().any(|line| line == "ignore_broadcast_ssid=1"));
        assert!(text.lines().any(|line| line == "ap_isolate=1"));
        assert!(text.lines().any(|line| line == "channel=11"));
    }

    #[test]
    fn a_validated_configuration_adds_no_extra_directive() {
        // Every value sits on its own line, so counting "key=" lines shows that
        // no value smuggled a second directive in.
        let text = render_hostapd_conf(&config());
        let keys: Vec<&str> = text
            .lines()
            .filter(|line| !line.starts_with('#'))
            .map(|line| line.split('=').next().unwrap())
            .collect();
        let mut unique = keys.clone();
        unique.sort_unstable();
        unique.dedup();
        assert_eq!(keys.len(), unique.len(), "a key appears twice: {keys:?}");
    }

    #[test]
    fn paths_and_units_are_derived_from_the_interface() {
        assert_eq!(conf_path("wlan0"), "/etc/hostapd/wlan0.conf");
        assert_eq!(unit_name("wlan0"), "hostapd@wlan0.service");
    }
}
