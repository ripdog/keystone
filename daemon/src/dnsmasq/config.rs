//! Dnsmasq configuration file generation

use keystone_core::{
    DnsmasqAddressAction, DnsmasqAddressOverride, DnsmasqCnameRecord, DnsmasqConfig,
    DnsmasqDhcpOption, DnsmasqDhcpRange, DnsmasqHostRecord, DnsmasqIpv6Mode, DnsmasqStateResponse,
    DnsmasqStaticLease, DnsmasqUpstreamMode,
};

/// Default dnsmasq configuration directory
pub const DNSMASQ_CONF_DIR: &str = "/etc/dnsmasq.d";

/// Main dnsmasq configuration file.
///
/// Keystone takes full ownership of this file when dnsmasq is enabled.
pub const DNSMASQ_MAIN_CONFIG_PATH: &str = "/etc/dnsmasq.conf";

/// Keystone's dnsmasq configuration file (legacy).
///
/// Kept for now so we can remove it during migration.
pub const DNSMASQ_CONFIG_PATH: &str = "/etc/dnsmasq.d/50-keystone.conf";

/// Dnsmasq lease file location
pub const DNSMASQ_LEASE_FILE: &str = "/var/lib/dnsmasq/dnsmasq.leases";

/// AdGuard Home default port for LocalAdGuard mode
pub const ADGUARD_DEFAULT_PORT: u16 = 5353;

/// Generate the complete dnsmasq configuration file content
pub fn generate_dnsmasq_config(state: &DnsmasqStateResponse) -> String {
    let mut lines = Vec::new();

    // Header
    lines.push("# Generated by Keystone - do not edit manually".to_string());
    lines.push("# Changes will be overwritten on next apply".to_string());
    lines.push(String::new());

    // Global settings
    generate_global_settings(&mut lines, &state.config);

    // Upstream DNS
    generate_upstream_dns(&mut lines, &state.config);

    // Interface binding
    generate_interface_binding(&mut lines, &state.config);

    // DHCP ranges
    generate_dhcp_ranges(&mut lines, &state.dhcp_ranges);

    // Static leases
    generate_static_leases(&mut lines, &state.static_leases);

    // DHCP options
    generate_dhcp_options(&mut lines, &state.dhcp_options);

    // Host records
    generate_host_records(&mut lines, &state.host_records);

    // CNAME records
    generate_cname_records(&mut lines, &state.cname_records);

    // Address overrides
    generate_address_overrides(&mut lines, &state.address_overrides);

    // Lease file
    lines.push(String::new());
    lines.push("# Lease file".to_string());
    lines.push(format!("dhcp-leasefile={}", DNSMASQ_LEASE_FILE));

    // Logging
    if state.config.log_queries {
        lines.push(String::new());
        lines.push("# Query logging enabled".to_string());
        lines.push("log-queries".to_string());
    }
    if state.config.log_dhcp {
        if !state.config.log_queries {
            lines.push(String::new());
        }
        lines.push("log-dhcp".to_string());
    }

    lines.join("\n")
}

/// Generate global DNS settings
fn generate_global_settings(lines: &mut Vec<String>, config: &DnsmasqConfig) {
    lines.push("# Global settings".to_string());

    // DNS port (0 disables DNS)
    if config.dns_port != 53 {
        lines.push(format!("port={}", config.dns_port));
    }

    // Cache size
    lines.push(format!("cache-size={}", config.cache_size));

    // Security settings
    if config.domain_needed {
        lines.push("domain-needed".to_string());
    }
    if config.bogus_priv {
        lines.push("bogus-priv".to_string());
    }

    // Local domain
    if let Some(ref domain) = config.local_domain {
        lines.push(format!("local=/{}/", domain));
        lines.push(format!("domain={}", domain));
        if config.expand_hosts {
            lines.push("expand-hosts".to_string());
        }
    }

    // DNSSEC
    if config.dnssec_enabled {
        lines.push("dnssec".to_string());
        lines.push("trust-anchor=.,20326,8,2,E06D44B80B8F1D39A95C0B0D7C65D08458E880409BBC683457104237C7F8EC8D".to_string());
    }

    lines.push(String::new());
}

/// Generate upstream DNS configuration
fn generate_upstream_dns(lines: &mut Vec<String>, config: &DnsmasqConfig) {
    lines.push("# Upstream DNS".to_string());

    match config.upstream_mode {
        DnsmasqUpstreamMode::System => {
            // Use system resolv.conf (default behavior, no config needed)
            lines.push("# Using system resolv.conf".to_string());
        }
        DnsmasqUpstreamMode::Custom => {
            lines.push("no-resolv".to_string());
            for server in &config.upstream_servers {
                let port_suffix = server
                    .port
                    .filter(|&p| p != 53)
                    .map(|p| format!("#{}", p))
                    .unwrap_or_default();

                if let Some(ref domain) = server.domain {
                    // Domain-specific server
                    lines.push(format!(
                        "server=/{}/{}{}",
                        domain, server.address, port_suffix
                    ));
                } else {
                    // General upstream server
                    lines.push(format!("server={}{}", server.address, port_suffix));
                }
            }
        }
        DnsmasqUpstreamMode::LocalAdGuard => {
            lines.push("no-resolv".to_string());
            lines.push(format!("server=127.0.0.1#{}", ADGUARD_DEFAULT_PORT));
            lines.push("# Chaining to local AdGuard Home".to_string());
        }
    }

    lines.push(String::new());
}

/// Generate interface binding configuration
fn generate_interface_binding(lines: &mut Vec<String>, config: &DnsmasqConfig) {
    lines.push("# Interface binding".to_string());

    // Bind mode
    if config.bind_dynamic {
        lines.push("bind-dynamic".to_string());
    }

    // Listen interfaces
    for iface in &config.listen_interfaces {
        lines.push(format!("interface={}", iface));
    }

    // Except interfaces
    for iface in &config.except_interfaces {
        lines.push(format!("except-interface={}", iface));
    }

    // No-DHCP interfaces (DNS only)
    for iface in &config.no_dhcp_interfaces {
        lines.push(format!("no-dhcp-interface={}", iface));
    }

    lines.push(String::new());
}

/// Generate DHCP range configurations
fn generate_dhcp_ranges(lines: &mut Vec<String>, ranges: &[DnsmasqDhcpRange]) {
    if ranges.is_empty() {
        return;
    }

    lines.push("# DHCP ranges".to_string());

    for range in ranges {
        if !range.enabled {
            continue;
        }

        // To scope pools per-interface, Keystone uses dnsmasq tags.
        // dnsmasq itself does *not* automatically bind DHCP to a tagged interface,
        // so we also emit `interface=<name>` to ensure DHCP is activated on that NIC.
        lines.push(format!("interface={}", range.interface));

        // Generate tag from interface name for filtering.
        // Keep this consistent with `interface=<name>` so dnsmasq can match tags.
        let tag = format!("set:{}", range.interface);

        // Build the dhcp-range line
        let mut parts = vec![tag.clone()];
        parts.push(range.start_address.clone());
        parts.push(range.end_address.clone());

        if let Some(ref netmask) = range.netmask {
            parts.push(netmask.clone());
        }

        parts.push(range.lease_time.clone());

        lines.push(format!("dhcp-range={}", parts.join(",")));

        // IPv6 range if configured
        if let Some(ipv6_mode) = range.ipv6_mode {
            let mode_flag = match ipv6_mode {
                DnsmasqIpv6Mode::RaOnly => "ra-only",
                DnsmasqIpv6Mode::RaStateless => "ra-stateless",
                DnsmasqIpv6Mode::Slaac => "slaac",
                DnsmasqIpv6Mode::Dhcpv6 => "dhcpv6",
            };

            if let Some(ref prefix) = range.ipv6_prefix {
                lines.push(format!("dhcp-range={},{},{}", tag, prefix, mode_flag));
            } else {
                // Use constructor mode for automatic prefix detection
                lines.push(format!(
                    "dhcp-range=::,constructor:{},{}",
                    range.interface, mode_flag
                ));
            }
        }
    }

    lines.push(String::new());
}

/// Generate static lease configurations
fn generate_static_leases(lines: &mut Vec<String>, leases: &[DnsmasqStaticLease]) {
    let enabled_leases: Vec<_> = leases.iter().filter(|l| l.enabled).collect();

    if enabled_leases.is_empty() {
        return;
    }

    lines.push("# Static leases".to_string());

    for lease in enabled_leases {
        // Build dhcp-host line
        // Format: dhcp-host=mac,set:tag1,set:tag2,ip,hostname,lease_time
        let mut parts = Vec::new();

        // MAC or client-id
        if let Some(ref client_id) = lease.client_id {
            parts.push(format!("id:{}", client_id));
        } else {
            parts.push(lease.mac_address.clone());
        }

        // Tags to set
        for tag in &lease.set_tags {
            parts.push(format!("set:{}", tag));
        }

        // IP address
        parts.push(lease.ip_address.clone());

        // Hostname
        if let Some(ref hostname) = lease.hostname {
            parts.push(hostname.clone());
        }

        // Lease time
        if let Some(ref lease_time) = lease.lease_time {
            parts.push(lease_time.clone());
        }

        lines.push(format!("dhcp-host={}", parts.join(",")));
    }

    lines.push(String::new());
}

/// Generate DHCP option configurations
fn generate_dhcp_options(lines: &mut Vec<String>, options: &[DnsmasqDhcpOption]) {
    let enabled_options: Vec<_> = options.iter().filter(|o| o.enabled).collect();

    if enabled_options.is_empty() {
        return;
    }

    lines.push("# DHCP options".to_string());

    for option in enabled_options {
        // Build dhcp-option line
        let mut parts = Vec::new();

        // Tag matching
        for tag in &option.match_tags {
            parts.push(format!("tag:{}", tag));
        }

        // Option prefix for IPv6 or force
        let option_prefix = if option.ipv6 { "option6:" } else { "option:" };

        // Option name/number and value
        parts.push(format!("{}{}", option_prefix, option.option));
        parts.push(option.value.clone());

        let directive = if option.force && !option.ipv6 {
            "dhcp-option-force"
        } else {
            "dhcp-option"
        };

        lines.push(format!("{}={}", directive, parts.join(",")));
    }

    lines.push(String::new());
}

/// Generate custom host records
fn generate_host_records(lines: &mut Vec<String>, records: &[DnsmasqHostRecord]) {
    let enabled_records: Vec<_> = records.iter().filter(|r| r.enabled).collect();

    if enabled_records.is_empty() {
        return;
    }

    lines.push("# Custom DNS records".to_string());

    for record in enabled_records {
        if record.hostnames.is_empty() {
            continue;
        }

        // Build host-record line
        // Format: host-record=hostname1,hostname2,...,ipv4,ipv6
        let mut parts: Vec<String> = record.hostnames.clone();

        if let Some(ref ipv4) = record.ipv4_address {
            parts.push(ipv4.clone());
        }
        if let Some(ref ipv6) = record.ipv6_address {
            parts.push(ipv6.clone());
        }

        // Add TTL if specified
        let ttl_suffix = record.ttl.map(|t| format!(",{}", t)).unwrap_or_default();

        lines.push(format!("host-record={}{}", parts.join(","), ttl_suffix));
    }

    lines.push(String::new());
}

/// Generate CNAME records
fn generate_cname_records(lines: &mut Vec<String>, records: &[DnsmasqCnameRecord]) {
    let enabled_records: Vec<_> = records.iter().filter(|r| r.enabled).collect();

    if enabled_records.is_empty() {
        return;
    }

    lines.push("# CNAME records".to_string());

    for record in enabled_records {
        // Format: cname=alias,target,ttl
        let ttl_suffix = record.ttl.map(|t| format!(",{}", t)).unwrap_or_default();

        lines.push(format!(
            "cname={},{}{}",
            record.alias, record.target, ttl_suffix
        ));
    }

    lines.push(String::new());
}

/// Generate address override configurations
fn generate_address_overrides(lines: &mut Vec<String>, overrides: &[DnsmasqAddressOverride]) {
    let enabled_overrides: Vec<_> = overrides.iter().filter(|o| o.enabled).collect();

    if enabled_overrides.is_empty() {
        return;
    }

    lines.push("# Address overrides (blocking/redirects)".to_string());

    for override_entry in enabled_overrides {
        match override_entry.action {
            DnsmasqAddressAction::Block => {
                // Return NXDOMAIN - empty address
                lines.push(format!("address=/{}/", override_entry.domain));
            }
            DnsmasqAddressAction::Null => {
                // Return 0.0.0.0 / ::
                lines.push(format!("address=/{}/0.0.0.0", override_entry.domain));
                lines.push(format!("address=/{}/::", override_entry.domain));
            }
            DnsmasqAddressAction::Redirect => {
                // Redirect to specific IP
                if let Some(ref addr) = override_entry.redirect_address {
                    lines.push(format!("address=/{}/{}", override_entry.domain, addr));
                }
            }
        }
    }

    lines.push(String::new());
}

#[cfg(test)]
mod tests {
    use super::*;
    use keystone_core::DnsmasqUpstreamServer;

    #[test]
    fn test_generate_basic_config() {
        let state = DnsmasqStateResponse {
            config: DnsmasqConfig::default(),
            dhcp_ranges: vec![],
            static_leases: vec![],
            dhcp_options: vec![],
            host_records: vec![],
            cname_records: vec![],
            address_overrides: vec![],
        };

        let config = generate_dnsmasq_config(&state);

        assert!(config.contains("Generated by Keystone"));
        assert!(config.contains("cache-size=1000"));
        assert!(config.contains("domain-needed"));
        assert!(config.contains("bogus-priv"));
        assert!(config.contains("local=/lan/"));
        assert!(config.contains("domain=lan"));
        assert!(config.contains("expand-hosts"));
    }

    #[test]
    fn test_generate_custom_upstream() {
        let state = DnsmasqStateResponse {
            config: DnsmasqConfig {
                upstream_mode: DnsmasqUpstreamMode::Custom,
                upstream_servers: vec![
                    DnsmasqUpstreamServer {
                        address: "1.1.1.1".to_string(),
                        port: None,
                        domain: None,
                    },
                    DnsmasqUpstreamServer {
                        address: "8.8.8.8".to_string(),
                        port: Some(53),
                        domain: None,
                    },
                ],
                ..Default::default()
            },
            dhcp_ranges: vec![],
            static_leases: vec![],
            dhcp_options: vec![],
            host_records: vec![],
            cname_records: vec![],
            address_overrides: vec![],
        };

        let config = generate_dnsmasq_config(&state);

        assert!(config.contains("no-resolv"));
        assert!(config.contains("server=1.1.1.1"));
        assert!(config.contains("server=8.8.8.8"));
    }

    #[test]
    fn test_generate_dhcp_range() {
        let state = DnsmasqStateResponse {
            config: DnsmasqConfig::default(),
            dhcp_ranges: vec![DnsmasqDhcpRange {
                id: Some(1),
                name: "LAN Pool".to_string(),
                interface: "br-lan".to_string(),
                start_address: "192.168.1.100".to_string(),
                end_address: "192.168.1.200".to_string(),
                netmask: Some("255.255.255.0".to_string()),
                lease_time: "24h".to_string(),
                enabled: true,
                ipv6_mode: None,
                ipv6_prefix: None,
            }],
            static_leases: vec![],
            dhcp_options: vec![],
            host_records: vec![],
            cname_records: vec![],
            address_overrides: vec![],
        };

        let config = generate_dnsmasq_config(&state);

        assert!(
            config.contains("dhcp-range=set:br-lan,192.168.1.100,192.168.1.200,255.255.255.0,24h")
        );
    }

    #[test]
    fn test_generate_static_lease() {
        let state = DnsmasqStateResponse {
            config: DnsmasqConfig::default(),
            dhcp_ranges: vec![],
            static_leases: vec![DnsmasqStaticLease {
                id: Some(1),
                mac_address: "00:11:22:33:44:55".to_string(),
                ip_address: "192.168.1.10".to_string(),
                hostname: Some("server1".to_string()),
                lease_time: Some("infinite".to_string()),
                client_id: None,
                set_tags: vec![],
                enabled: true,
            }],
            dhcp_options: vec![],
            host_records: vec![],
            cname_records: vec![],
            address_overrides: vec![],
        };

        let config = generate_dnsmasq_config(&state);

        assert!(config.contains("dhcp-host=00:11:22:33:44:55,192.168.1.10,server1,infinite"));
    }

    #[test]
    fn test_generate_address_override_block() {
        let state = DnsmasqStateResponse {
            config: DnsmasqConfig::default(),
            dhcp_ranges: vec![],
            static_leases: vec![],
            dhcp_options: vec![],
            host_records: vec![],
            cname_records: vec![],
            address_overrides: vec![DnsmasqAddressOverride {
                id: Some(1),
                domain: "ads.example.com".to_string(),
                action: DnsmasqAddressAction::Block,
                redirect_address: None,
                enabled: true,
            }],
        };

        let config = generate_dnsmasq_config(&state);

        assert!(config.contains("address=/ads.example.com/"));
    }
}
